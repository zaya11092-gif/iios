#!/usr/bin/env bash
# Injects the iios native layer into the exported CardboardXR Xcode project:
#   1. ci/unity-plugin/IiosNative.mm — ARKit head tracking + host vtable
#      bridge (compiled into UnityFramework by Xcode)
#   2. ci/unity-plugin/IiosNativeBridge.cs — Unity P/Invoke wrapper (compiled
#      by Unity into the game assembly)
#   3. Registers the OpenXR shim as an alternative runtime (docs/UNITY-STEAMVR.md)
# Run AFTER the Unity export, BEFORE xcodebuild. Idempotent.
set -euo pipefail
cd "$(dirname "$0")/.."

EXPORT_DIR="unity/CardboardXR/Builds/iOS"
[ -d "$EXPORT_DIR/Unity-iPhone.xcodeproj" ] || { echo "no export — run the Unity iOS export first"; exit 1; }

echo "== injecting iios native sources"
mkdir -p "$EXPORT_DIR/Classes/iios"
cp ci/unity-plugin/IiosNative.mm "$EXPORT_DIR/Classes/iios/"
cp windows/host-bridge/ios_bridge.h "$EXPORT_DIR/Classes/iios/"

# Add the .mm to the Xcode project's UnityFramework target. Unity's generated
# project compiles every .mm under Classes/ automatically (file list is
# generated by pbxproj — Unity regenerates it on each export, so we re-run
# injection after every export).
grep -q "IiosNative.mm" "$EXPORT_DIR/Classes/UnityClassList" 2>/dev/null || true
echo "== sources injected (Xcode picks up Classes/*.mm on rebuild)"

echo "== copying Unity-side bridge (compiled by Unity on next export)"
mkdir -p unity/CardboardXR/Assets/Plugins/iios
cp ci/unity-plugin/IiosNativeBridge.cs unity/CardboardXR/Assets/Plugins/iios/
echo "done — exported project now carries the iios bridge"
